class InflateBudget:
    """Decompressed metadata allowed for ONE image, summed over all its chunks (bomb-safe: many chunks that each
    stay under a per-chunk cap must not add up)."""

    def __init__(self, limit: int = MAX_FILE_BYTES):
        self.left = limit

    def inflate(self, data: bytes) -> bytes:
        out = zlib.decompressobj().decompress(data, self.left + 1)
        if len(out) > self.left:
            raise ValueError("compressed metadata expands beyond 5 MB in total")
        self.left -= len(out)
        return out


# PNG chunks that hold only pixels or small fixed-format numbers; every other chunk is metadata.
PNG_PIXEL_CHUNKS = frozenset({b"IHDR", b"PLTE", b"IDAT", b"tRNS", b"gAMA", b"cHRM", b"sRGB", b"sBIT", b"bKGD",
                              b"hIST", b"pHYs", b"tIME", b"acTL", b"fcTL", b"fdAT"})


def png_parts(data: bytes) -> tuple[list[tuple[str, str]], bytes]:
    """(metadata texts, pixel bytes) of a PNG; ValueError if the chunk structure is broken."""
    meta: list[tuple[str, str]] = []
    pixels = []
    budget = InflateBudget()
    i, n = 8, len(data)
    while True:
        if i + 12 > n:
            raise ValueError("PNG ends without IEND")
        length = int.from_bytes(data[i:i + 4], "big")
        ctype = data[i + 4:i + 8]
        if i + 12 + length > n or not ctype.isalpha():
            raise ValueError("broken PNG chunk")
        payload = data[i + 8:i + 8 + length]
        i += 12 + length
        if ctype == b"IEND":
            break
        if ctype in PNG_PIXEL_CHUNKS:
            pixels.append(payload)
            continue
        label = ctype.decode("latin-1")
        kw, _, rest = payload.partition(b"\x00")
        if ctype == b"tEXt":
            meta.append((label, (kw + b": " + rest).decode("latin-1")))
        elif ctype in (b"zTXt", b"iCCP"):
            meta.append((label, kw.decode("latin-1") + ": " + lossy_text(budget.inflate(rest[1:]))))
        elif ctype == b"iTXt":
            flag = rest[:1] == b"\x01"
            lang, _, rest2 = rest[2:].partition(b"\x00")
            tkw, _, text = rest2.partition(b"\x00")
            body = budget.inflate(text) if flag else text
            meta.append((label, b" ".join((kw, lang, tkw)).decode("utf-8", "replace") + ": "
                         + body.decode("utf-8", "replace")))
        else:
            meta.append((label, lossy_text(payload)))
    if i < n:
        meta.append(("after-IEND", lossy_text(data[i:])))
    return meta, b"".join(pixels)


JPEG_NEXT_MARKER_RE = re.compile(rb"\xff[^\x00\xd0-\xd7]")


def jpeg_parts(data: bytes) -> tuple[list[tuple[str, str]], bytes]:
    """(metadata texts, pixel bytes) of a JPEG: COM and APPn segments (EXIF, XMP, ICC, IPTC, ...) and anything
    after EOI are metadata; tables and entropy-coded scans are pixels. ValueError if the structure is broken."""
    meta: list[tuple[str, str]] = []
    pixels = []
    i, n = 2, len(data)
    while True:
        if i >= n or data[i] != 0xFF:
            raise ValueError("broken JPEG marker")
        while i < n and data[i] == 0xFF:
            i += 1
        if i >= n:
            raise ValueError("JPEG ends without EOI")
        marker = data[i]
        i += 1
        if marker == 0xD9:  # EOI
            break
        if 0xD0 <= marker <= 0xD7 or marker == 0x01:
            continue
        if i + 2 > n:
            raise ValueError("broken JPEG segment")
        length = int.from_bytes(data[i:i + 2], "big")
        if length < 2 or i + length > n:
            raise ValueError("broken JPEG segment")
        payload = data[i + 2:i + length]
        i += length
        if marker == 0xFE or 0xE0 <= marker <= 0xEF:
            meta.append(("COM" if marker == 0xFE else f"APP{marker - 0xE0}", lossy_text(payload)))
            continue
        pixels.append(payload)
        if marker == 0xDA:  # SOS: entropy-coded data up to the next real marker (not FF00 stuffing or RSTn)
            m = JPEG_NEXT_MARKER_RE.search(data, i)
            j = m.start() if m else n
            pixels.append(data[i:j])
            i = j
    if i < n:
        meta.append(("after-EOI", lossy_text(data[i:])))
    return meta, b"".join(pixels)


