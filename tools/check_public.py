def git(args: list[str], *, cwd: str | None = None, env: dict[str, str] | None = None,
        check: bool = True) -> subprocess.CompletedProcess[bytes]:
    proc = subprocess.run(["git", *args], cwd=cwd, env=env, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, stdin=subprocess.DEVNULL)
    if check and proc.returncode != 0:
        msg = proc.stderr.decode("utf-8", "replace").strip()
        raise UsageError(f"git {' '.join(args[:3])} failed: {msg}")
    return proc


class BlobReader:
    """One long-lived `git cat-file --batch` process for reading blobs by sha."""

    def __init__(self, cwd: str | None = None, env: dict[str, str] | None = None):
        self._proc = subprocess.Popen(["git", "cat-file", "--batch"], cwd=cwd, env=env,
                                      stdin=subprocess.PIPE, stdout=subprocess.PIPE)

    def read(self, sha: str) -> bytes:
        assert self._proc.stdin and self._proc.stdout
        self._proc.stdin.write(sha.encode() + b"\n")
        self._proc.stdin.flush()
        header = self._proc.stdout.readline().decode().split()
        if len(header) < 3 or header[1] == "missing":
            raise UsageError(f"git object missing: {sha}")
        size = int(header[2])
        data = self._proc.stdout.read(size)
        self._proc.stdout.read(1)  # trailing LF
        return data

    def close(self) -> None:
        if self._proc.stdin:
            self._proc.stdin.close()
        self._proc.wait(timeout=30)


