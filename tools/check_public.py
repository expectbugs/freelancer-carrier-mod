def looks_utf16_nobom(data: bytes) -> str | None:
    sample = data[:4096]
    if len(sample) < 16:
        return None
    even, odd = sample[0::2], sample[1::2]
    z_even = even.count(0) / len(even)
    z_odd = odd.count(0) / max(len(odd), 1)
    if z_odd >= 0.4 and z_even <= 0.05:
        return "utf-16-le"
    if z_even >= 0.4 and z_odd <= 0.05:
        return "utf-16-be"
    return None


def decode_text(data: bytes) -> str | None:
    """Return text, or None for binary data (NUL bytes that are not UTF-16 text)."""
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        try:
            return data.decode("utf-16")
        except UnicodeDecodeError:
            return data.decode("utf-16", errors="replace")
    if b"\x00" not in data:
        return data.decode("utf-8", errors="replace")
    enc = looks_utf16_nobom(data)
    if enc:
        return data[: len(data) - (len(data) % 2)].decode(enc, errors="replace")
    return None


def lossy_text(data: bytes) -> str:
    """Printable view of binary data, NULs as line breaks, so text rules still apply."""
    return data.decode("latin-1").replace("\x00", "\n")


def sniff(data: bytes) -> tuple[str, str]:
    """Classify content whatever the file name: (category, label)."""
    head = data[:64]
    has_nul = b"\x00" in head
    if data.startswith((b"PK\x03\x04", b"PK\x05\x06")):
        return "archive", "zip"
    if data.startswith(b"\x1f\x8b"):
        return "archive", "gzip"
    if data.startswith(b"\xfd7zXZ\x00"):
        return "archive", "xz"
    if data.startswith(b"BZh") and len(data) > 4 and data[3:4] in b"123456789" and data[4:10] == b"1AY&SY":
        return "archive", "bzip2"
    if len(data) > 262 and data[257:262] == b"ustar":
        return "archive", "tar"
    for magic, label, extra in UNVETTABLE_MAGIC:
        if data.startswith(magic) and (extra is None or extra(data)):
            return "unvettable", label
    if data[:2] == b"MZ" and has_nul:
        return "pe", "PE executable/DLL"
    if data.startswith(b"RIFF") and data[8:12] == b"WAVE":
        return "game", "RIFF/WAVE audio"
    if data.startswith(b"RIFF") and data[8:12] == b"WEBP":
        return "image", "webp"
    for magic, label, need_nul in GAME_MAGIC:
        if data.startswith(magic) and (has_nul or not need_nul):
            return "game", label
    if (data.startswith(FONT_MAGIC) and has_nul) or (data.startswith(b"\x00\x01\x00\x00") and len(data) > 16
                                                     and all(32 <= c < 127 for c in data[12:16])):
        return "font", "font"
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image", "png"
    if data.startswith(b"\xff\xd8\xff"):
        return "image", "jpeg"
    if data.startswith((b"GIF87a", b"GIF89a")):
        return "image", "gif"
    if data.startswith(b"BM") and len(data) >= 6 and int.from_bytes(data[2:6], "little") == len(data):
        return "image", "bmp"
    if data.startswith((b"II*\x00", b"MM\x00*")):
        return "image", "tiff"
    if data.startswith(b"8BPS") and data[4:6] in (b"\x00\x01", b"\x00\x02"):  # PSD/PSB version
        return "image", "psd"
    if data.startswith(b"\x00\x00\x01\x00") and len(data) > 6 and 0 < int.from_bytes(data[4:6], "little") < 64:
        return "image", "ico"
    text = decode_text(data)
    if text is not None:
        return "text", "text"
    return "binary", "unknown binary"


class LineIndex:
    def __init__(self, text: str):
        self._starts = [0]
        pos = text.find("\n")
        while pos != -1:
            self._starts.append(pos + 1)
            pos = text.find("\n", pos + 1)

    def line_of(self, offset: int) -> int:
        return bisect.bisect_right(self._starts, offset)


