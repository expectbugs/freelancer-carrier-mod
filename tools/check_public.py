def file_entry(abs_path: str, rel: str) -> Entry | None:
    try:
        st = os.lstat(abs_path)
    except FileNotFoundError:
        return None
    if os.path.islink(abs_path):
        target = os.readlink(abs_path).encode("utf-8", "surrogateescape")
        return Entry(rel, len(target), (lambda t=target: t), symlink=True)
    if not os.path.isfile(abs_path):
        return None

    def load(p: str = abs_path) -> bytes:
        with open(p, "rb") as fh:
            return fh.read()

    return Entry(rel, st.st_size, load)


def walk_entries(root: str, *, skip_worktrees: bool) -> list[Entry]:
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = os.path.relpath(dirpath, root)
        rel_dir = "" if rel_dir == "." else rel_dir.replace(os.sep, "/") + "/"
        keep = []
        for d in dirnames:
            full = os.path.join(dirpath, d)
            if d == ".git" or (skip_worktrees and (rel_dir + d + "/") == SKIP_TREE_PREFIX):
                continue
            if os.path.islink(full):
                ent = file_entry(full, rel_dir + d)  # symlink to dir: vet the link itself
                if ent:
                    out.append(ent)
                continue
            keep.append(d)
        dirnames[:] = sorted(keep)
        for f in sorted(filenames):
            ent = file_entry(os.path.join(dirpath, f), rel_dir + f)
            if ent:
                out.append(ent)
    return out


def git_toplevel(path: str | None, env: dict[str, str] | None) -> str | None:
    proc = git(["rev-parse", "--is-inside-work-tree"], cwd=path, env=env, check=False)
    if proc.returncode != 0 or proc.stdout.strip() != b"true":
        return None
    return git(["rev-parse", "--show-toplevel"], cwd=path, env=env).stdout.decode().strip()


def tree_entries(path: str, warn: Callable[[str], None]) -> tuple[list[Entry], str]:
    if not os.path.isdir(path):
        raise UsageError(f"--tree: not a directory: {path}")
    env = clean_git_env()
    top = git_toplevel(path, env)
    if top is None:
        return walk_entries(path, skip_worktrees=True), "directory walk (not a git work tree)"
    raw = git(["ls-files", "-co", "--exclude-standard", "--full-name", "-z"], cwd=path, env=env).stdout
    seen = set()
    out = []
    for item in raw.decode("utf-8", "surrogateescape").split("\0"):
        if not item or item in seen:
            continue
        seen.add(item)
        if item.startswith(SKIP_TREE_PREFIX):
            continue
        if item.endswith("/"):
            warn(f"embedded git repository not scanned: {item}")
            continue
        ent = file_entry(os.path.join(top, item), item)
        if ent:
            out.append(ent)
    if not out and git(["check-ignore", "-q", "."], cwd=path, env=env, check=False).returncode == 0:
        raise UsageError(f"--tree: {path} is ignored by git, so nothing would be scanned; vet a non-git copy "
                         "(the directory walk mode) instead")
    return out, f"git ls-files -co --exclude-standard in {top}"


def index_map(top: str) -> dict[str, tuple[str, str]]:
    raw = git(["ls-files", "-s", "-z"], cwd=top).stdout.decode("utf-8", "surrogateescape")
    out = {}
    for item in raw.split("\0"):
        if not item:
            continue
        meta, path = item.split("\t", 1)
        mode, sha, stage = meta.split()
        if stage == "0":
            out[path] = (mode, sha)
    return out


def object_sizes(shas: list[str], top: str) -> dict[str, int]:
    if not shas:
        return {}
    proc = subprocess.run(["git", "cat-file", "--batch-check"], input=("\n".join(shas) + "\n").encode(),
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE, cwd=top)
    if proc.returncode != 0:
        raise UsageError("git cat-file --batch-check failed")
    out = {}
    for line in proc.stdout.decode().splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] == "blob":
            out[parts[0]] = int(parts[2])
    return out


def staged_entries(reader: BlobReader, top: str) -> tuple[list[Entry], Listing]:
    imap = index_map(top)
    has_head = git(["rev-parse", "--verify", "-q", "HEAD"], cwd=top, check=False).returncode == 0
    if has_head:
        raw = git(["diff", "--cached", "--name-only", "--no-renames", "--diff-filter=ACMRT", "-z", "HEAD"],
                  cwd=top).stdout
        changed = [p for p in raw.decode("utf-8", "surrogateescape").split("\0") if p]
    else:
        changed = sorted(imap)
    blob_paths = {p: v for p, v in imap.items() if v[0] != "160000"}
    sizes = object_sizes(sorted({sha for _, sha in blob_paths.values()}), top)

    def make(p: str) -> Entry:
        mode, sha = blob_paths[p]
        return Entry(p, sizes.get(sha, 0), (lambda s=sha: reader.read(s)), symlink=(mode == "120000"))

    listing = Listing(make(p) for p in blob_paths)
    entries = [listing.get(p) for p in changed if p in blob_paths]
    return [e for e in entries if e is not None], listing


def commit_tree_entries(commit: str, reader: BlobReader, seen: set[tuple[str, str]]) -> tuple[list[Entry], Listing]:
    raw = git(["ls-tree", "-r", "-l", "-z", "--full-tree", commit]).stdout.decode("utf-8", "surrogateescape")
    all_entries = []
    fresh = []
    for item in raw.split("\0"):
        if not item:
            continue
        meta, path = item.split("\t", 1)
        mode, otype, sha, size = meta.split()
        if otype != "blob":
            continue
        ent = Entry(path, int(size), (lambda s=sha: reader.read(s)), display=f"{commit[:10]}:{path}",
                    symlink=(mode == "120000"))
        all_entries.append(ent)
        if (path, sha) not in seen:
            seen.add((path, sha))
            fresh.append(ent)
    return fresh, Listing(all_entries)


def check_identity(scanner: Scanner, short: str, role: str, email: str) -> None:
    if not email_allowed(email, False) or not EMAIL_RE.fullmatch(email):
        scanner.add(f"{short}:<{role}>", "R6-identity", f"{role} email is not a noreply/placeholder address")


def scan_commit_metadata(scanner: Scanner, rev_args: list[str]) -> int:
    fmt = "%H%x1f%an%x1f%ae%x1f%cn%x1f%ce%x1f%B%x1e"
    raw = git(["log", f"--format={fmt}", *rev_args]).stdout.decode("utf-8", "replace")
    n = 0
    for rec in raw.split("\x1e"):
        rec = rec.strip("\n")
        if not rec:
            continue
        sha, an, ae, cn, ce, body = rec.split("\x1f", 5)
        n += 1
        short = sha[:10]
        check_identity(scanner, short, "commit author", ae)
        check_identity(scanner, short, "commit committer", ce)
        ident = f"{an}\n{cn}\n{body}"
        scanner.scan_text(Entry("<commit-message>", len(ident), lambda: b"", display=f"{short}:<commit message>"),
                          ident, "")
    return n


def scan_tag_objects(scanner: Scanner, rev_args: list[str]) -> int:
    """Annotated tags named in the rev arguments: tagger identity and message."""
    n = 0
    for tok in rev_args:
        if tok.startswith("-"):
            continue
        for part in re.split(r"\.\.\.?", tok.lstrip("^")):
            if not part:
                continue
            if git(["cat-file", "-t", part], check=False).stdout.strip() != b"tag":
                continue
            body = git(["cat-file", "tag", part]).stdout.decode("utf-8", "replace")
            head, _, msg = body.partition("\n\n")
            short = git(["rev-parse", "--short=10", part]).stdout.decode().strip()
            m = re.search(r"^tagger (.*) <([^>]*)>", head, re.M)
            if m:
                check_identity(scanner, short, "tagger", m.group(2))
            text = (m.group(1) if m else "") + "\n" + msg
            scanner.scan_text(Entry("<tag-message>", len(text), lambda: b"", display=f"{short}:<tag message>"),
                              text, "")
            n += 1
    return n


