def inline_pairs(line: str, code: bool) -> list[tuple[str, str]]:
    """Quoted-key and flow-style pairs anywhere in a line; long lines are read in bounded, overlapping chunks
    (a pair is counted in the chunk where it starts)."""
    rxs = (QUOTED_PAIR_CODE_RE, FLOW_PAIR_CODE_RE) if code else (QUOTED_PAIR_RE, FLOW_PAIR_RE)
    if "'" not in line and '"' not in line and "{" not in line and "," not in line:
        return []
    out: list[tuple[str, str]] = []
    n = len(line)
    start = 0
    while start < n:
        seg = line[start:start + R5_CHUNK + R5_CHUNK_OVERLAP]
        limit = R5_CHUNK if start + R5_CHUNK < n else len(seg)
        for rx in rxs:
            for m in rx.finditer(seg):
                if m.start() < limit:
                    out.append((m.group(1), m.group(2)))
        start += R5_CHUNK
    return out


def table_columns(line: str, sep: str) -> list[str]:
    cells = line.strip().strip("|").split(sep) if sep == "|" else line.split(sep)
    return [c.strip().strip("\"'`* ") for c in cells]


def distinctive_columns(cols: list[str]) -> int:
    # Only FL-distinctive column names count: system/faction/level-style columns are our own data too.
    return sum(1 for c in cols if re.fullmatch(_KEY, c) and is_distinctive_key(c))


def count_table_rows(lines: list[str], start: int, sep: str, ncols: int) -> int:
    rows = 0
    for ln in lines[start:]:
        if not ln.strip() or TABLE_COMMENT_RE.match(ln) or (sep == "|" and PIPE_RULE_RE.match(ln)):
            continue
        if ln.count(sep) >= max(ncols - 1, 1):
            rows += 1
        else:
            break
    return rows


def table_rows(text: str, lines: list[str]) -> int:
    """Rows of the largest table whose header has >= R5_TABLE_FL_COLUMNS FL-distinctive columns: a CSV/TSV
    header in the first non-blank, non-comment lines; a Markdown pipe table or an HTML table anywhere."""
    best = 0
    seen = 0
    for i, ln in enumerate(lines):
        if seen >= R5_TABLE_HEADER_LINES:
            break
        if not ln.strip() or TABLE_COMMENT_RE.match(ln):
            continue
        seen += 1
        if len(ln) > R5_TABLE_MAX_HEADER:
            continue
        for sep in TABLE_SEPS:
            if ln.count(sep) >= 2:
                cols = table_columns(ln, sep)
                if distinctive_columns(cols) >= R5_TABLE_FL_COLUMNS:
                    best = max(best, count_table_rows(lines, i + 1, sep, len(cols)))
    for i, ln in enumerate(lines):
        if "|" in ln and len(ln) <= R5_TABLE_MAX_HEADER and ln.count("|") >= 2:
            cols = table_columns(ln, "|")
            if distinctive_columns(cols) >= R5_TABLE_FL_COLUMNS:
                best = max(best, count_table_rows(lines, i + 1, "|", len(cols)))
    for m in HTML_TABLE_RE.finditer(text):
        end = HTML_TABLE_END_RE.search(text, m.end())
        body = text[m.end():end.start() if end else len(text)]
        rows = [r.start() for r in HTML_ROW_RE.finditer(body)]
        if len(rows) < 2:
            continue
        head = body[rows[0]:rows[1]][:R5_TABLE_MAX_HEADER * 4]
        cols = [HTML_TAG_RE.sub("", c).strip() for c in HTML_CELL_RE.findall(head)]
        if distinctive_columns(cols) >= R5_TABLE_FL_COLUMNS:
            best = max(best, len(rows) - 1)
    return best if best >= R5_TABLE_ROWS else 0


def fl_data_features(path: str, text: str) -> dict:
    ext = ext_of(path)
    code = ext in CODE_EXTS
    d = g = h = v = k = bare = 0
    lines = text.splitlines()
    for line in lines:
        head = line[:R5_LONG_LINE]
        pairs: list[tuple[str, str]] = []
        m = SECTION_LINE_RE.match(head)
        if m:
            h += 1
            continue
        if len(line) <= R5_LONG_LINE and (QUOTED_VECTOR_LINE_RE if code else BARE_VECTOR_LINE_RE).match(line):
            bare += 1
            v += 1
            continue
        m = INI_FORM_RE.match(head)
        if m:
            val = m.group(2).split(";", 1)[0].strip()
            if not code or (val and FL_VALUE_RE.match(val)):
                pairs.append((m.group(1), val))
        elif not code:
            m = YAML_FORM_RE.match(head)
            if m:
                pairs.append((m.group(1), (m.group(2) or "").strip()))
        pairs.extend(inline_pairs(line, code))
        for key, val in pairs:
            k += 1
            if is_distinctive_key(key):
                d += 1
            elif key.lower() in FL_GENERIC_KEYS:
                g += 1
            elif key.lower() in FL_SECTION_KEYS:
                h += 1
            n_vec = len(VECTOR_IN_LIST_RE.findall(val)) if val.startswith("[") else 0
            if n_vec > 1:
                v += n_vec
            elif val and FL_SHAPED_VALUE_RE.search(val.strip().strip("\"'")):
                v += 1
    table = 0 if code else table_rows(text, lines)
    return {"distinctive": d, "generic": g, "sections": h, "shaped": v, "keys": k, "bare_vectors": bare,
            "table_rows": table, "code": code, "score": d + g // 4 + 2 * h + v // 2 + table}


def marker_reason(raw: str | None) -> str:
    reason = (raw or "").strip().strip("\"',;:*/#<>!-").strip()
    return reason if re.search(r"[A-Za-z0-9]", reason) else ""


def authored_data_header(text: str) -> tuple[int, str] | None:
    """(line number, reason) of a whole-comment-line marker in the first AUTHORED_DATA_LINES lines."""
    for n, line in enumerate(text.split("\n", AUTHORED_DATA_LINES)[:AUTHORED_DATA_LINES], 1):
        m = AUTHORED_DATA_LINE_RE.match(line[:1000])
        if m:
            return n, marker_reason(m.group(1))
    return None


def asset_ref_lines(text: str) -> list[int]:
    """Non-comment lines holding a game asset file reference or a backslash path."""
    out = []
    for n, line in enumerate(text.splitlines(), 1):
        if COMMENT_LINE_RE.match(line):
            continue
        if BACKSLASH_PATH_RE.search(line) or any(
                not m.group(1).lower().startswith(OWN_NAME_PREFIX) for m in ASSET_REF_RE.finditer(line)):
            out.append(n)
    return out


def authored_data_allowed(path: str) -> bool:
    return path.startswith(AUTHORED_DATA_PREFIXES) or bool(AUTHORED_DATA_SRC_TESTS_RE.match(path))


def fl_data_verdict(path: str, text: str) -> str | None:
    f = fl_data_features(path, text)
    fl_keys = f["distinctive"] + f["generic"]
    if f["distinctive"] >= R5_DISTINCTIVE_MIN:
        return f"{f['distinctive']} lines with FL-distinctive keys"
    if f["sections"] >= R5_BLOCKS_MIN and fl_keys >= R5_BLOCKS_KEYS_MIN:
        return f"{f['sections']} [Section] lines with {fl_keys} FL key lines"
    # In code, sections need FL key pairs (the rule above): a "section" key in patch ops or configs is ordinary.
    if not f["code"] and f["sections"] >= R5_SECTIONS_MIN and f["keys"] >= R5_SECTION_KEYS_MIN:
        return f"{f['sections']} [Section] lines with {f['keys']} key lines"
    if f["shaped"] >= R5_SHAPED_MIN and fl_keys >= R5_SHAPED_KEYS_MIN:
        return f"{f['shaped']} FL-shaped values with {fl_keys} FL key lines"
    if f["shaped"] >= R5_DENSE_SHAPED_MIN and 2 * f["shaped"] >= f["keys"] + f["bare_vectors"]:
        return f"{f['shaped']} FL-shaped values (vectors, FL file refs, hardpoints) in {f['keys']} key lines"
    if f["table_rows"]:
        return f"a table with FL columns and {f['table_rows']} rows"
    return None


