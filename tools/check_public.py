class Scanner:
    def __init__(self, blocklist: list[BlockEntry], *, allow_binaries: bool = False, release: bool = False,
                 index: RefIndex | None = None):
        self.blocklist = blocklist
        self.allow_binaries = allow_binaries
        self.release = release
        self.index = index
        self.violations: list[Violation] = []
        self.warnings: list[str] = []
        self.escapes: list[tuple[str, str]] = []  # (display, marker) of files accepted as authored data
        self.files_scanned = 0

    # -- reporting ----------------------------------------------------------

    def masked(self, display: str) -> str:
        # Every occurrence is masked, word entries included (more than they match, never less).
        low = display.lower()
        if not any(b.lit in low for b in self.blocklist):
            return display
        out = display
        for b in self.blocklist:
            out = re.sub(re.escape(b.lit), "***", out, flags=re.I)
        return out

    def add(self, entry: Entry | str, rule: str, message: str) -> None:
        display = entry.display if isinstance(entry, Entry) else entry
        self.violations.append(Violation(self.masked(display), rule, message))

    # -- per entry ------------------------------------------------------------

    def scan_entries(self, entries: list[Entry], listing: Listing, depth: int = 0) -> None:
        for e in entries:
            self.scan_entry(e, listing, depth)

    def scan_entry(self, e: Entry, listing: Listing, depth: int = 0) -> None:
        self.files_scanned += 1
        path = e.path
        low = path.lower()
        ext = ext_of(path)

        self.check_path(e)
        if e.size > MAX_FILE_BYTES:
            self.add(e, "R1-size", f"file is {e.size} bytes (> 5 MB limit)")
            return
        if e.symlink:
            if self.release:
                self.add(e, "R1-symlink", "release assets must be regular files, not symlinks")
                return
            # Git stores the link target string, never the target's content.
            self.scan_text(e, e.load().decode("utf-8", "replace"), ext)
            return

        binary_ok = False
        if ext in FORBIDDEN_EXTS or ext in EXTRA_FORBIDDEN_EXTS:
            if ext in RELEASE_BINARY_EXTS and self.allow_binaries:
                binary_ok = True
            else:
                hint = " (allowed only in --release with --allow-binaries)" if ext in RELEASE_BINARY_EXTS else ""
                self.add(e, "R1-ext", f"forbidden file type '{ext}' (game asset, binary, shader, font or dump){hint}")
                return
        if ext in UNVETTABLE_ARCHIVE_EXTS:
            self.add(e, "R1-archive", f"archive type '{ext}' cannot be vetted with the stdlib")
            return

        data = e.load()
        cat, label = sniff(data)
        if cat == "archive" or (cat != "text" and (low.endswith(ZIP_EXTS) or is_tar_name(low))):
            self.scan_archive(e, data, label, depth)
            return
        if cat == "unvettable":
            self.add(e, "R1-archive", f"{label} archive content cannot be vetted with the stdlib")
            return
        if cat == "pe":
            if not binary_ok:
                self.add(e, "R1-magic", f"{label} content (by signature, whatever the name)")
            self.scan_binary(e, data)
            return
        if cat in ("game", "font"):
            self.add(e, "R1-magic", f"{label} content (by signature, whatever the name)")
            self.scan_binary(e, data)
            return
        if ext in IMAGE_EXTS or cat == "image":
            vetted = self.check_image(e, ext, label if cat == "image" else None, listing)
            if cat != "text":
                if vetted:
                    self.scan_vetted_image(e, data, label, listing, depth)
                else:
                    self.scan_binary(e, data)
                return
        if cat == "binary":
            self.add(e, "R1-binary", "binary content; the repo is source-only (allowed: vetted images under docs/, "
                     "--release DLLs)")
            self.scan_binary(e, data)
            return

        text = decode_text(data) or ""
        if ext == ".ini":
            self.check_ini(e, text)
        self.scan_text(e, text, ext)
        self.scan_base64(e, text, listing, depth)
        if ext != ".ini":
            why = fl_data_verdict(path, text)
            if why:
                self.report_fl_data(e, text, why, listing, depth)
        if self.index is not None:
            self.check_index(e, text)

    def authored_data_marker(self, e: Entry, text: str, listing: Listing) -> tuple[str, str] | None:
        """(where, reason) of the file's authored-data marker (D112), or None. reason '' = no usable reason."""
        sib = listing.get(e.path + AUTHORED_DATA_SUFFIX)
        if sib is not None:
            note = decode_text(sib.load()[:4096]) or ""
            first = next((ln for ln in note.splitlines() if ln.strip()), "")
            return f"sibling {posixpath.basename(sib.path)}", marker_reason(first)
        if ext_of(e.path) in AUTHORED_DATA_SIBLING_ONLY_EXTS:
            return None
        hdr = authored_data_header(text)
        if hdr is not None:
            return f"comment line {hdr[0]}", hdr[1]
        return None

    def report_fl_data(self, e: Entry, text: str, why: str, listing: Listing, depth: int) -> None:
        """R5 on a plain text file: a violation, or a warning under the authored-data marker (D108, D112)."""
        marker = self.authored_data_marker(e, text, listing)
        note = ""
        if marker is not None:
            where, reason = marker
            if not reason:
                note = f" The authored-data marker ({where}) has no reason, so it does not apply."
            elif depth > 0 or not authored_data_allowed(e.path):
                note = (f" The authored-data marker ({where}) has no effect here: it is accepted only under "
                        f"{AUTHORED_DATA_WHERE}.")
            else:
                refs = asset_ref_lines(text)
                if refs:
                    self.add(e, "R5-fl-data", f"authored-data marker ({where}) present, but vanilla game asset file "
                             f"references or backslash paths appear at {fmt_lines(refs)}. The marker is only for our "
                             f"own values: refer to vanilla content by nickname; only our own generated assets "
                             f"({OWN_NAME_PREFIX}* file names, CONVENTIONS §2) may be named by file.")
                    return
                self.escapes.append((self.masked(e.display), where))
                self.warnings.append(f"{self.masked(e.display)}: [R5-fl-data] looks like FL game data ({why}); "
                                     f"accepted as our own authored data via the authored-data marker ({where}); "
                                     "reviewers check its reason")
                return
        self.add(e, "R5-fl-data", f"looks like FL game data: {why}. Never commit game data or extracts. The "
                 "authored-data marker is only for our own values that use FL-native key names in bulk: a whole "
                 f"comment line '# check_public: authored-data <reason>' in the first {AUTHORED_DATA_LINES} lines, or "
                 f"a sibling file '<file>{AUTHORED_DATA_SUFFIX}' holding the reason (the only form for JSON), accepted "
                 f"only under {AUTHORED_DATA_WHERE} (D108, D112). Small authored INI fixtures belong in "
                 "tests/fixtures-authored/*.ini (rule R2)." + note)

    def check_path(self, e: Entry) -> None:
        low = e.path.lower()
        hits = [i for i, b in enumerate(self.blocklist, 1) if b.in_text(low)]
        if hits:
            self.add(e, "R4-blocklist", f"file path contains local blocklist entry #{hits[0]}")
        for label, rx in IP_RULES:
            for m in rx.finditer(e.path):
                ip = normalized_ip(m.group(0))
                if ip not in RANGE_BASE_IPS and not (under(e.path, SYNTHETIC_OK_PREFIXES) and ip in SYNTHETIC_IPS):
                    self.add(e, "R4-ip", f"file path contains a private/CGNAT IPv4 address ({label})")
                    break
        for m in EMAIL_RE.finditer(e.path):
            if not email_allowed(m.group(0), under(e.path, SYNTHETIC_OK_PREFIXES)):
                self.add(e, "R4-email", "file path contains an email address")
                break
        bad_dirs = [p for p in low.split("/")[:-1] if p in FORBIDDEN_DIRS]
        if bad_dirs:
            self.add(e, "R3-path", f"under forbidden directory '{bad_dirs[0]}/' (local/build/vendor/refs/... "
                     "content never goes public)")
        if low.endswith(SAVE_SIDECAR_SUFFIX):
            self.add(e, "R3-save-sidecar", "*.carrier.json save sidecar")

    def check_image(self, e: Entry, ext: str, kind: str | None, listing: Listing) -> bool:
        """R1-image; True when the image is a vetted docs/ image."""
        problems = []
        if ext not in DOC_IMAGE_EXTS or (kind is not None and kind not in DOC_IMAGE_KINDS):
            what = kind or ext or "untyped"
            problems.append(f"'{what}' image content/type is never allowed (possible game texture); only PNG/JPEG "
                            "named .png/.jpg/.jpeg")
        if not e.path.startswith("docs/"):
            problems.append("images are allowed only under docs/")
        if e.size > MAX_IMAGE_BYTES:
            problems.append(f"image is {e.size} bytes (> 512 KB)")
        if not problems:
            stem = posixpath.splitext(e.path)[0]
            note = None
            for cand in (e.path + ".source", stem + ".source"):
                sib = listing.get(cand)
                if sib is not None:
                    note = sib
                    break
            if note is None:
                problems.append("missing sibling <name>.source provenance file")
            else:
                text = decode_text(note.load()) or ""
                if not SOURCE_NOTE_RE.search(text):
                    problems.append(f"{note.path} does not say 'generated by ...' or 'own work'")
        if problems:
            self.add(e, "R1-image", "; ".join(problems))
        return not problems

    def check_ini(self, e: Entry, text: str) -> None:
        if not under(e.path, INI_ALLOWED_PREFIXES):
            self.add(e, "R2-ini-location", ".ini files are allowed only under " + ", ".join(INI_ALLOWED_PREFIXES))
        n = len(INI_ANY_HEADER_RE.findall(text))
        if n > INI_HEADER_LIMIT:
            self.add(e, "R2-ini-headers", f"{n} [Section] header lines (> {INI_HEADER_LIMIT}): looks like game data")

    def check_index(self, e: Entry, text: str) -> None:
        assert self.index is not None
        res = self.index.best_match(text)
        if res is None:
            return
        matched, total, ref = res
        share = matched / total
        if not r7_trips(matched, total):
            return
        msg = f"{matched} of {total} normalised {SHINGLE_K}-line shingles ({share:.0%}) match reference file {ref}"
        repo = ref.split("/", 1)[0]
        m = DERIVED_FROM_RE.search("\n".join(text.splitlines()[:30]))
        if m and m.group(1).lower() == repo.lower() and repo.lower() not in NON_ESCAPABLE_REFS:
            self.warnings.append(f"{self.masked(e.display)}: [R7-refs-copy] {msg}; accepted via 'derived-from "
                                 f"{m.group(1)} {m.group(2)}' header (keep the attribution and license)")
            return
        hint = "" if repo.lower() in NON_ESCAPABLE_REFS else (
            f"; if this is a licensed, attributed snippet add a header line 'check_public: derived-from {repo} "
            "<SPDX-license>'")
        self.add(e, "R7-refs-copy", msg + hint)

    # -- archives -------------------------------------------------------------

    def scan_archive(self, e: Entry, data: bytes, kind: str, depth: int) -> None:
        if depth >= MAX_ARCHIVE_DEPTH:
            self.add(e, "R1-archive", f"archive nested deeper than {MAX_ARCHIVE_DEPTH} levels")
            return
        low = e.path.lower()
        members: list[tuple[str, int, Callable[[], bytes], bool]] = []
        try:
            if kind == "zip" or (kind not in ("gzip", "bzip2", "xz", "tar") and low.endswith(ZIP_EXTS)):
                zf = zipfile.ZipFile(io.BytesIO(data))
                for info in zf.infolist():
                    if info.is_dir():
                        continue
                    members.append((info.filename, info.file_size, (lambda i=info: zf.read(i)), False))
            elif kind == "tar" or (kind in ("gzip", "bzip2", "xz") and self._is_tar(data)) or \
                    (kind not in ("gzip", "bzip2", "xz") and is_tar_name(low)):
                tf = tarfile.open(fileobj=io.BytesIO(data), mode="r:*")
                for m in tf.getmembers():
                    if m.isdir():
                        continue
                    if m.issym() or m.islnk():
                        members.append((m.name, len(m.linkname), (lambda m=m: m.linkname.encode()), True))
                    elif m.isfile():
                        members.append((m.name, m.size, (lambda m=m: tf.extractfile(m).read()), False))
            elif kind in ("gzip", "bzip2", "xz"):
                inner = bounded_decompress(kind, data)
                ext = ext_of(e.path)
                inner_path = e.path[: -len(ext)] if ext in (".gz", ".bz2", ".xz") else e.path + ".unpacked"
                if len(inner) > MAX_FILE_BYTES:
                    self.add(e, "R1-size", f"{kind} content decompresses to more than 5 MB")
                    return
                sub = Entry(inner_path, len(inner), (lambda d=inner: d),
                            display=f"{e.display}!{posixpath.basename(inner_path)}")
                self.scan_entry(sub, Listing([sub]), depth + 1)
                return
            else:
                self.add(e, "R1-archive", "archive could not be opened for vetting")
                return
        except (zipfile.BadZipFile, tarfile.TarError, OSError, EOFError, lzma.LZMAError, ValueError) as exc:
            self.add(e, "R1-archive", f"archive could not be opened for vetting ({type(exc).__name__})")
            return
        names = [clean_member_name(m[0]) for m in members]
        prefix = ""
        if names:
            first = names[0].split("/", 1)[0]
            if all("/" in n and n.split("/", 1)[0] == first for n in names):
                prefix = first + "/"
        subs = []
        for (name, size, loader, is_link), clean in zip(members, names):
            rel = clean[len(prefix):] if prefix else clean
            subs.append(Entry(rel, size, loader, display=f"{e.display}!{clean}", symlink=is_link))
        self.scan_entries(subs, Listing(subs), depth + 1)

    @staticmethod
    def _is_tar(data: bytes) -> bool:
        try:
            with tarfile.open(fileobj=io.BytesIO(data), mode="r:*") as tf:
                return tf.next() is not None  # an all-zero stream is not a tar worth trusting
        except (tarfile.TarError, OSError, EOFError, lzma.LZMAError, ValueError):
            return False

    # -- content --------------------------------------------------------------

    def scan_vetted_image(self, e: Entry, data: bytes, kind: str, listing: Listing, depth: int) -> None:
        """Metadata (PNG text/other ancillary chunks, JPEG COM/APPn, trailing bytes) gets every text rule; pixel
        data gets the reduced set (blocklist, real secret shapes, R5)."""
        try:
            meta, pixels = png_parts(data) if kind == "png" else jpeg_parts(data)
        except (ValueError, zlib.error) as exc:
            self.add(e, "R1-image", f"malformed {kind.upper()} ({exc}): its metadata cannot be vetted")
            self.scan_binary(e, data)
            return
        self.scan_binary(e, pixels, vetted_image=True)
        for label, text in meta:
            sub = Entry(e.path, len(text), lambda: b"", display=f"{e.display}!{label}")
            self.scan_text(sub, text, "")
            self.scan_base64(sub, text, listing, depth + 1)
            why = fl_data_verdict(e.path, text)
            if why:
                self.add(sub, "R5-fl-data", f"image metadata holds FL game data: {why}")

    def scan_binary(self, e: Entry, data: bytes, vetted_image: bool = False) -> None:
        low = data.lower()
        for i, b in enumerate(self.blocklist, 1):
            if b.in_bytes(low):
                self.add(e, "R4-blocklist", f"binary content contains local blocklist entry #{i}")
        text = lossy_text(data)
        if vetted_image:
            # Compressed image bytes match the short generic patterns (addresses, IPs, token prefixes) by
            # chance; a vetted docs/ image gets the blocklist, real secret shapes and R5 only.
            for label, rx in SECRET_SHAPE_RES:
                if rx.search(text):
                    self.add(e, "R4-secret", f"{label} in binary content")
        else:
            self.scan_text(e, text, ext_of(e.path), binary=True)
        why = fl_data_verdict(e.path, text)
        if why:
            self.add(e, "R5-fl-data", f"binary content holds FL game data: {why}")

    def scan_base64(self, e: Entry, text: str, listing: Listing, depth: int) -> None:
        lines = text.splitlines()
        blocks: list[tuple[int, str]] = []
        i = 0
        while i < len(lines):
            j = i
            while j < len(lines) and BASE64_LINE_RE.match(lines[j]):
                j += 1
            if j - i >= 3:  # a wrapped base64 block
                blocks.append((i + 1, "".join(ln.strip() for ln in lines[i:j])))
                i = j
                continue
            for m in BASE64_TOKEN_RE.finditer(lines[i]):  # or one long token on a line
                blocks.append((i + 1, m.group(0)))
            i += 1
        for line_no, blob in blocks[:50]:
            if HEX_RE.fullmatch(blob):
                continue  # hex digests are not base64 payloads
            try:
                raw = binascii.a2b_base64(blob + "=" * (-len(blob) % 4))
            except (binascii.Error, ValueError):
                continue
            if len(raw) < BASE64_MIN_DECODED:
                continue
            cat, label = sniff(raw)
            if cat == "text":
                sub = Entry(e.path, len(raw), (lambda d=raw: d), display=f"{e.display}!base64@{line_no}")
                if depth < MAX_ARCHIVE_DEPTH:
                    self.scan_text(sub, decode_text(raw) or "", ext_of(e.path))
                    why = fl_data_verdict(e.path, decode_text(raw) or "")
                    if why:
                        self.add(sub, "R5-fl-data", f"base64-encoded FL game data: {why}")
                continue
            self.add(e, "R1-embedded", f"base64 block at line {line_no} decodes to {label} ({len(raw)} bytes)")
            if cat == "archive" and depth < MAX_ARCHIVE_DEPTH:
                sub = Entry(e.path + ".b64", len(raw), (lambda d=raw: d), display=f"{e.display}!base64@{line_no}")
                self.scan_archive(sub, raw, label, depth + 1)

    def scan_text(self, e: Entry, text: str, ext: str, binary: bool = False) -> None:
        idx = LineIndex(text)
        path = e.path
        lowtext = text.lower()
        plan_doc = under(path, PLAN_DOC_PREFIXES)
        where = "binary content" if binary else "content"

        # Blocklist literals (binary hits are reported by scan_binary).
        if not binary:
            for i, b in enumerate(self.blocklist, 1):
                lines = []
                for pos in b.positions(lowtext):
                    lines.append(idx.line_of(pos))
                    if len(lines) >= 50:
                        break
                if lines:
                    self.add(e, "R4-blocklist", f"contains local blocklist entry #{i} at {fmt_lines(lines)}")

        # Private / CGNAT IPs.
        synthetic_ok = under(path, SYNTHETIC_OK_PREFIXES)
        for label, rx in IP_RULES:
            lines = []
            for m in rx.finditer(text):
                ip = normalized_ip(m.group(0))
                if ip in RANGE_BASE_IPS or (synthetic_ok and ip in SYNTHETIC_IPS):
                    continue
                lines.append(idx.line_of(m.start()))
            if lines:
                self.add(e, "R4-ip", f"private/CGNAT IPv4 address ({label}) in {where} at {fmt_lines(lines)}")

        # Emails (not SSH clone URLs) and tailnet host names.
        lines = [idx.line_of(m.start()) for m in EMAIL_RE.finditer(text)
                 if not email_allowed(m.group(0), synthetic_ok) and not is_git_ssh_url(text, m)]
        if lines:
            self.add(e, "R4-email", f"email address (not noreply/placeholder) in {where} at {fmt_lines(lines)}")
        lines = [idx.line_of(m.start()) for m in TAILNET_HOST_RE.finditer(text)]
        if lines:
            self.add(e, "R4-host", f"Tailscale MagicDNS host name in {where} at {fmt_lines(lines)}")

        # Secrets: real shapes everywhere; bare identifiers/prefixes outside plan docs.
        for label, rx in SECRET_SHAPE_RES:
            lines = [idx.line_of(m.start()) for m in rx.finditer(text)]
            if lines:
                self.add(e, "R4-secret", f"{label} in {where} at {fmt_lines(lines)}")
        if not plan_doc:
            lines = []
            for needle in SECRET_IDENTIFIERS + TOKEN_PREFIXES:
                pos = text.find(needle)
                while pos != -1:
                    lines.append(idx.line_of(pos))
                    pos = text.find(needle, pos + 1)
            for rx in SECRET_IDENTIFIER_RES + (PRIVATE_KEY_LOOSE_RE,):
                lines += [idx.line_of(m.start()) for m in rx.finditer(text)]
            if lines:
                self.add(e, "R4-secret", f"credential marker (key/token/personal-config identifier) in {where} at "
                         f"{fmt_lines(lines)}")

            lines = [idx.line_of(m.start()) for m in PERSONAL_PROJECT_RE.finditer(text)]
            if lines:
                self.add(e, "R4-personal-project", f"reference to the owner's other projects in {where} at "
                         f"{fmt_lines(lines)}")

        # Decompiled code: anywhere except docs/ and NOTES*/README* documentation files (D106).
        if not may_cite_decomp(path, ext):
            m = DECOMP_RE.search(text)
            if m:
                self.add(e, "R4-decomp", f"decompilation marker in {where} at line {idx.line_of(m.start())} (cite "
                         "reference sources only in docs/ or a NOTES*/README* file)")


def may_cite_decomp(path: str, ext: str) -> bool:
    """docs/ (plan docs included), and documentation files in the ledger (state/) or named NOTES*/README*."""
    if path.startswith("docs/"):
        return True
    return ext in DOC_EXTS and (path.startswith("state/")
                                or posixpath.basename(path).upper().startswith(DOC_NAME_PREFIXES))


def is_git_ssh_url(text: str, m: re.Match[str]) -> bool:
    """git@<host>:owner/repo (scp-like) or ssh://git@<host>/... is a clone URL, not an address."""
    if not m.group(0).lower().startswith(GIT_SSH_LOCAL):
        return False
    return text[m.end():m.end() + 1] == ":" or text[max(0, m.start() - 6):m.start()].lower() == "ssh://"


def email_allowed(addr: str, synthetic_ok: bool) -> bool:
    low = addr.lower()
    domain = low.rsplit("@", 1)[1]
    if domain in ALLOWED_EMAIL_DOMAINS:
        return True
    if any(domain == d or domain.endswith("." + d) for d in PLACEHOLDER_EMAIL_DOMAINS):
        return True
    return synthetic_ok and low in SYNTHETIC_EMAILS


