class BlockEntry:
    """One local blocklist literal (lowercased). 'w:<literal>' entries match only as whole words (D108)."""

    def __init__(self, raw: str):
        self.word = raw[:2].lower() == "w:"
        self.lit = (raw[2:].strip() if self.word else raw).lower()
        if self.word:
            pre = r"(?<!\w)" if re.match(r"\w", self.lit[:1]) else ""
            post = r"(?!\w)" if re.match(r"\w", self.lit[-1:]) else ""
            self._rx = re.compile(pre + re.escape(self.lit) + post)
            bpre = b"(?<![0-9a-z_])" if pre else b""
            bpost = b"(?![0-9a-z_])" if post else b""
            u8 = re.escape(self.lit.encode("utf-8"))
            self._rx8 = re.compile(bpre + u8 + bpost)
            wpre = b"(?<![0-9a-z_]\x00)" if pre else b""
            wpost = b"(?![0-9a-z_]\x00)" if post else b""
            self._rx16 = re.compile(wpre + re.escape(self.lit.encode("utf-16-le")) + wpost)

    def positions(self, low: str) -> Iterable[int]:
        """Start offsets of every match in already-lowercased text."""
        if self.word:
            for m in self._rx.finditer(low):
                yield m.start()
            return
        pos = low.find(self.lit)
        while pos != -1:
            yield pos
            pos = low.find(self.lit, pos + 1)

    def in_text(self, low: str) -> bool:
        return next(iter(self.positions(low)), None) is not None

    def in_bytes(self, low: bytes) -> bool:
        """UTF-8 or UTF-16LE occurrence in already-lowercased (ASCII) bytes."""
        if self.word:
            return bool(self._rx8.search(low) or self._rx16.search(low))
        return self.lit.encode("utf-8") in low or self.lit.encode("utf-16-le") in low


def load_blocklist(explicit: str | None) -> tuple[list[BlockEntry], str | None]:
    """Return (entries, path used) or ([], None) if none was found."""
    for cand in blocklist_candidates(explicit):
        if os.path.isfile(cand):
            with open(cand, encoding="utf-8", errors="replace") as fh:
                entries = []
                for raw in fh:
                    line = raw.strip()
                    if line and not line.startswith("#"):
                        ent = BlockEntry(line)
                        if ent.lit:
                            entries.append(ent)
            return entries, cand
    if explicit:
        raise UsageError(f"blocklist not found: {explicit}")
    return [], None


