def norm_lines(text: str) -> list[str]:
    out = []
    for line in text.splitlines():
        s = line.strip().lstrip(">-*+#;/ \t")
        s = NORM_STRIP_RE.sub("", s.lower())
        if len(s) >= NORM_MIN_LEN:
            out.append(s)
    return out


def r7_trips(matched: int, total: int) -> bool:
    return (matched / total >= R7_SHARE and matched >= R7_MIN_MATCH) or matched >= R7_ABS_MATCH


def split_long_lines(text: str) -> str | None:
    """Minified/compact data re-broken into one item per line, the way an indented dump of it reads
    (break after ',', '[' and '{', and before ']' and '}', never inside a string); None if no line is
    longer than R7_SPLIT_LINE. Query side only: it lets a one-line copy match an indented reference."""
    lines = text.split("\n")
    if not any(len(ln) > R7_SPLIT_LINE for ln in lines):
        return None
    out: list[str] = []
    for ln in lines:
        if len(ln) <= R7_SPLIT_LINE:
            out.append(ln)
            continue
        cur: list[str] = []
        for m in SPLIT_TOKEN_RE.finditer(ln):
            tok = m.group(0)
            if tok in ("]", "}"):
                out.append("".join(cur))
                cur = [tok]
            elif tok in (",", "[", "{"):
                cur.append(tok)
                out.append("".join(cur))
                cur = []
            else:
                cur.append(tok)
        out.append("".join(cur))
    return "\n".join(out)


def shingles(text: str) -> set[int]:
    """40-bit hashes of every window of SHINGLE_K consecutive normalised lines."""
    lines = norm_lines(text)
    out = set()
    for i in range(len(lines) - SHINGLE_K + 1):
        h = hashlib.blake2b("\n".join(lines[i:i + SHINGLE_K]).encode("utf-8", "replace"), digest_size=5)
        out.add(int.from_bytes(h.digest(), "little"))
    return out


class RefIndex:
    """Sorted array of packed (40-bit shingle hash << 24 | 24-bit ref-file id) keys."""

    def __init__(self, directory: str):
        with open(os.path.join(directory, "meta.json"), encoding="utf-8") as fh:
            self.meta = json.load(fh)
        if self.meta.get("version") != INDEX_VERSION or self.meta.get("k") != SHINGLE_K:
            raise UsageError(f"index at {directory} has an old format; rebuild it with --build-index")
        self.files: list[str] = self.meta["files"]
        self.keys = array.array("Q")
        with open(os.path.join(directory, "keys.bin"), "rb") as fh:
            self.keys.frombytes(fh.read())

    def best_match(self, text: str) -> tuple[int, int, str] | None:
        """(matched shingles, query shingles, ref file) for the best single ref file, over the text as written
        and, when it has very long lines, re-broken one item per line."""
        cands = [self._best_match(shingles(text))]
        split = split_long_lines(text)
        if split is not None:
            cands.append(self._best_match(shingles(split)))
        found = [c for c in cands if c is not None]
        return max(found, key=lambda c: (r7_trips(*c[:2]), c[0] / c[1])) if found else None

    def _best_match(self, q: set[int]) -> tuple[int, int, str] | None:
        if not q:
            return None
        counts: dict[int, int] = {}
        keys, n = self.keys, len(self.keys)
        for h in q:
            lo = h << 24
            i = bisect.bisect_left(keys, lo)
            hi = lo | 0xFFFFFF
            while i < n and keys[i] <= hi:
                fid = keys[i] & 0xFFFFFF
                counts[fid] = counts.get(fid, 0) + 1
                i += 1
        if not counts:
            return None
        fid, best = max(counts.items(), key=lambda kv: kv[1])
        return best, len(q), self.files[fid]


def iter_ref_files(roots: list[tuple[str, str]]) -> Iterable[tuple[str, str]]:
    """Yield (label, absolute path) for indexable text files under the reference roots."""
    for root, label_prefix in roots:
        if not os.path.isdir(root):
            continue
        tops = sorted(os.listdir(root)) if label_prefix is None else [None]
        for top in tops:
            base = os.path.join(root, top) if top else root
            if top and (INDEX_SKIP_TOP.match(top) or not os.path.isdir(base)):
                continue
            label_top = top if top else label_prefix
            for dirpath, dirnames, filenames in os.walk(base):
                dirnames[:] = sorted(d for d in dirnames if d.lower() not in INDEX_SKIP_DIRS)
                for f in sorted(filenames):
                    full = os.path.join(dirpath, f)
                    if INDEX_SKIP_NAME_RE.search(f) or os.path.splitext(f)[1].lower() in INDEX_BINARY_EXTS:
                        continue
                    try:
                        if os.path.islink(full) or os.path.getsize(full) > INDEX_MAX_FILE:
                            continue
                    except OSError:
                        continue
                    rel = os.path.relpath(full, base).replace(os.sep, "/")
                    yield f"{label_top}/{rel}", full


def build_index(directory: str, refs: list[str], research: list[str], out: Callable[[str], None]) -> int:
    t0 = time.time()
    roots = [(r, None) for r in refs] + [(r, "local-research") for r in research]
    files: list[str] = []
    keys = array.array("Q")
    for label, full in iter_ref_files(roots):
        try:
            with open(full, "rb") as fh:
                data = fh.read()
        except OSError:
            continue
        text = decode_text(data)
        if text is None:
            continue
        sh = shingles(text)
        if not sh:
            continue
        fid = len(files)
        if fid >= 0xFFFFFF:
            raise UsageError("too many reference files for the index format")
        files.append(label)
        keys.extend((h << 24) | fid for h in sh)
    ordered = sorted(keys)
    del keys
    # Drop boilerplate (license headers, generated docs): shingles shared by many reference
    # files across several repos. Duplicates inside one game-data repo (HDE's near-identical
    # room files) are kept: they are still game data.
    repo_of = [f.split("/", 1)[0] for f in files]
    kept = array.array("Q")
    dropped = 0
    i, n = 0, len(ordered)
    while i < n:
        h = ordered[i] >> 24
        j = i + 1
        while j < n and (ordered[j] >> 24) == h:
            j += 1
        count = j - i
        if count > INDEX_HARD_CAP or (count > INDEX_MAX_FILES_PER_SHINGLE and len(
                {repo_of[ordered[x] & 0xFFFFFF] for x in range(i, j)}) >= INDEX_BOILERPLATE_REPOS):
            dropped += 1
        else:
            kept.extend(ordered[i:j])
        i = j
    del ordered
    tmp = directory.rstrip("/") + ".tmp"
    os.makedirs(tmp, exist_ok=True)
    with open(os.path.join(tmp, "keys.bin"), "wb") as fh:
        kept.tofile(fh)
    meta = {"version": INDEX_VERSION, "k": SHINGLE_K, "created": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "refs": refs, "research": research, "files": files, "entries": len(kept),
            "dropped_common_shingles": dropped}
    with open(os.path.join(tmp, "meta.json"), "w", encoding="utf-8") as fh:
        json.dump(meta, fh)
    os.makedirs(directory, exist_ok=True)
    for name in ("keys.bin", "meta.json"):
        os.replace(os.path.join(tmp, name), os.path.join(directory, name))
    os.rmdir(tmp)
    out(f"check_public: index built at {directory}: {len(files)} reference files, {len(kept)} shingle entries "
        f"({dropped} common shingles dropped), {os.path.getsize(os.path.join(directory, 'keys.bin')) >> 20} MiB, "
        f"in {time.time() - t0:.1f}s")
    return 0


