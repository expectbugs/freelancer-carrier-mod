def explain() -> None:
    print("check_public.py rules (REQ-P0-REPO-4; CONVENTIONS §5, §11; DECISIONS D101, D102, D106, D108):")
    for rid, text in RULES_EXPLAINED:
        print(f"  {rid}: {text}")
    print("Modes: --staged (index content of staged files), --tree PATH, --release DIR [--allow-binaries], "
          "--commits=REVS, --build-index. Exit codes: 0 clean, 1 violations, 2 usage/internal error.")


def run(argv: list[str]) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.explain:
        explain()
        return 0
    if not (args.staged or args.tree or args.release or args.commits or args.build_index):
        parser.print_usage(sys.stderr)
        print("check_public.py: error: one of --staged, --tree, --release, --commits, --build-index, --explain is "
              "required", file=sys.stderr)
        return 2
    if args.allow_binaries and not args.release:
        print("check_public.py: error: --allow-binaries is only valid with --release", file=sys.stderr)
        return 2

    def warn(msg: str) -> None:
        print(f"check_public: WARNING: {msg}", file=sys.stderr)

    if args.build_index:
        refs = args.refs or [os.environ.get("FLMOD_REFS") or DEFAULT_REFS]
        research = args.research if args.research is not None else [
            os.environ.get("FLMOD_RESEARCH") or os.path.join(local_dir(), "research")]
        return build_index(index_dir(args.index), refs, [r for r in research if os.path.isdir(r)], print)

    blocklist, bl_path = load_blocklist(args.blocklist)
    if bl_path is None:
        warn("local blocklist not found; personal-literal rule disabled (generic rules still apply)")
    index = None
    idir = index_dir(args.index)
    if os.path.isfile(os.path.join(idir, "meta.json")):
        index = RefIndex(idir)
    else:
        if args.index:
            raise UsageError(f"index not found: {args.index}")
        warn(f"reference fingerprint index not found at {idir}; rule R7 (other mods'/decomp/HDE copies) disabled "
             "(build it with --build-index)")

    scanner = Scanner(blocklist, allow_binaries=args.allow_binaries, release=bool(args.release), index=index)
    source = ""
    reader: BlobReader | None = None
    empty_is_error = False
    try:
        if args.staged:
            top = git_toplevel(None, None)
            if top is None:
                raise UsageError("--staged: not inside a git work tree")
            reader = BlobReader(cwd=top)
            entries, listing = staged_entries(reader, top)
            source = "staged files (index content)"
            scanner.scan_entries(entries, listing)
            scanned = [e.display for e in entries]
        elif args.tree:
            entries, source = tree_entries(args.tree, warn)
            scanner.scan_entries(entries, Listing(entries))
            scanned = [e.display for e in entries]
            empty_is_error = True
        elif args.release:
            if not os.path.isdir(args.release):
                raise UsageError(f"--release: not a directory: {args.release}")
            entries = walk_entries(args.release, skip_worktrees=False)
            source = f"release assets in {args.release}" + (" (binaries allowed)" if args.allow_binaries else "")
            scanner.scan_entries(entries, Listing(entries))
            scanned = [e.display for e in entries]
            empty_is_error = True
        else:
            rev_args = args.commits.split()
            commits = git(["rev-list", *rev_args]).stdout.decode().split()
            reader = BlobReader()
            seen: set[tuple[str, str]] = set()
            scanned = []
            for c in commits:
                fresh, listing = commit_tree_entries(c, reader, seen)
                scanner.scan_entries(fresh, listing)
                scanned += [e.display for e in fresh]
            n_meta = scan_commit_metadata(scanner, rev_args) if commits else 0
            n_tags = scan_tag_objects(scanner, rev_args)
            source = (f"{len(commits)} commit(s) from rev-list {' '.join(rev_args)} ({n_meta} commit headers/messages,"
                      f" {n_tags} annotated tag(s))")
    except UsageError as exc:
        print(f"check_public: ERROR: {exc}", file=sys.stderr)
        return 2
    finally:
        if reader is not None:
            reader.close()

    if args.verbose:
        for d in scanned:
            print(f"  scanned {scanner.masked(d)}")
    for w in scanner.warnings:
        warn(w)
    # Every file accepted under the authored-data marker, one stable line each (CI summaries list them).
    for display, where in scanner.escapes:
        print(f"check_public: AUTHORED-DATA {display} ({where})")
    for v in scanner.violations:
        print(f"FAIL {v.display}: [{v.rule}] {v.message}")
    bad_files = len({v.display for v in scanner.violations})
    if scanner.violations:
        print(f"check_public: FAIL: {len(scanner.violations)} violation(s) in {bad_files} file(s); "
              f"{scanner.files_scanned} file(s) scanned from {source}. See --explain.")
        return 1
    if scanner.files_scanned == 0:
        if empty_is_error:
            print(f"check_public: ERROR: nothing to scan ({source})", file=sys.stderr)
            return 2
        warn(f"no files to check ({source})")
    print(f"check_public: OK: {scanner.files_scanned} file(s) clean ({source})")
    return 0


def main() -> int:
    if sys.version_info < (3, 11):
        print("check_public.py needs Python 3.11+", file=sys.stderr)
        return 2
    try:
        return run(sys.argv[1:])
    except UsageError as exc:
        print(f"check_public: ERROR: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:  # fail closed on anything unexpected
        print(f"check_public: INTERNAL ERROR ({type(exc).__name__}): {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
